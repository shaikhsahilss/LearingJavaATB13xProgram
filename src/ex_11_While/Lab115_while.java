package ex_11_While;

public class Lab115_while {
    public static void main(String[] args) {
        int i = 0;
        while (i < 10) {
            System.out.println(i);
            i++;
        }

        int j = 0;
        for(; j <10; j++){
            System.out.println(j);
        }
    }
}
